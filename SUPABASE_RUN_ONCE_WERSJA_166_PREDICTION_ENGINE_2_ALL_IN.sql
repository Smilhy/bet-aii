create table if not exists public.match_model_experiments (
  id bigint generated by default as identity primary key,
  fixture_id text not null,
  fixture_date timestamptz null,
  home_team text not null default '',
  away_team text not null default '',
  league text not null default '',
  country text not null default '',
  model_role text not null,
  model_version text not null,
  active_at_capture boolean not null default false,
  data_quality integer not null default 0 check (data_quality >= 0 and data_quality <= 100),
  forecast jsonb not null default '{}'::jsonb,
  status text not null default 'pending',
  fixture_status text null,
  actual_home_goals integer null,
  actual_away_goals integer null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  settled_at timestamptz null,

  constraint match_model_experiments_role_check
    check (model_role in ('champion','challenger')),
  constraint match_model_experiments_status_check
    check (status in ('pending','settled','void')),
  constraint match_model_experiments_unique_variant
    unique (fixture_id, model_role, model_version)
);

create index if not exists idx_match_model_experiments_fixture
  on public.match_model_experiments(fixture_id);

create index if not exists idx_match_model_experiments_role_status
  on public.match_model_experiments(model_role, status, settled_at desc);

create index if not exists idx_match_model_experiments_version_status
  on public.match_model_experiments(model_version, status, settled_at desc);

create index if not exists idx_match_model_experiments_league
  on public.match_model_experiments(league, model_role, settled_at desc);

alter table public.match_model_experiments enable row level security;

