create table if not exists public.match_shadow_bets (
  id bigint generated by default as identity primary key,
  fixture_id text not null,
  fixture_date timestamptz null,
  home_team text not null default '',
  away_team text not null default '',
  league text not null default '',
  country text not null default '',
  market_key text not null,
  market_label text not null default '',
  bookmaker text not null default '',
  odds numeric(10,4) not null check (odds > 1),
  model_version text not null default 'BETAI_FORECAST_V152',
  raw_probability numeric(7,3) null,
  calibrated_probability numeric(7,3) null,
  uncertainty_pp numeric(7,3) null,
  conservative_probability numeric(7,3) null,
  fair_odds numeric(10,4) null,
  no_vig_probability numeric(7,3) null,
  edge_pp numeric(8,3) null,
  expected_value_pct numeric(9,3) null,
  reliability integer null check (reliability is null or (reliability >= 0 and reliability <= 100)),
  league_trust integer null check (league_trust is null or (league_trust >= 0 and league_trust <= 100)),
  drift_status text not null default 'PENDING',
  stake_units numeric(10,4) not null default 1.0000 check (stake_units > 0),
  decision text not null default 'BET',
  status text not null default 'pending',
  profit_units numeric(12,4) null,
  actual_home_goals integer null,
  actual_away_goals integer null,
  closing_odds numeric(10,4) null,
  clv_pct numeric(9,3) null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  settled_at timestamptz null,
  constraint match_shadow_bets_unique_signal unique (fixture_id, market_key, bookmaker, model_version),
  constraint match_shadow_bets_status_check check (status in ('pending','won','lost','void'))
);

create index if not exists idx_match_shadow_bets_fixture
  on public.match_shadow_bets(fixture_id);

create index if not exists idx_match_shadow_bets_status_date
  on public.match_shadow_bets(status, fixture_date);

create index if not exists idx_match_shadow_bets_league_market
  on public.match_shadow_bets(league, market_key, settled_at desc);

create index if not exists idx_match_shadow_bets_model
  on public.match_shadow_bets(model_version, settled_at desc);

alter table public.match_shadow_bets enable row level security;

comment on table public.match_shadow_bets is
  'Bet+AI V151 Shadow Portfolio: automatyczne paper bets 1u z decyzji BET. Nie stawia prawdziwych pieniędzy.';

comment on column public.match_shadow_bets.conservative_probability is
  'Prawdopodobieństwo po kalibracji i odjęciu marginesu niepewności V148.';

comment on column public.match_shadow_bets.profit_units is
  'Wynik paper betu: wygrany=(odds-1)*stake, przegrany=-stake.';

