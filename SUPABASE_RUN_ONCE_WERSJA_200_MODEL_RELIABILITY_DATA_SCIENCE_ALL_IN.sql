-- ============================================================
-- V182 — APPEND-ONLY PREDICTION FREEZE LEDGER
-- ============================================================
create table if not exists public.match_prediction_freeze_ledger (
  id bigint generated by default as identity primary key,
  fixture_id text not null,
  fixture_date timestamptz null,
  home_team text not null default '',
  away_team text not null default '',
  league text not null default '',
  country text not null default '',
  season_key text null,
  captured_at timestamptz not null default now(),
  generated_at timestamptz null,
  input_cutoff_at timestamptz not null default now(),
  model_version text not null,
  active_model text not null default 'champion',
  data_quality integer not null default 0 check (data_quality between 0 and 100),
  freeze_hash text not null unique,
  selected_for_backtest boolean not null default false,
  selection_reason text not null default '',
  forecast jsonb not null default '{}'::jsonb,
  integrity jsonb not null default '{}'::jsonb
);

create index if not exists idx_match_prediction_freeze_fixture_time
  on public.match_prediction_freeze_ledger(fixture_id, captured_at desc);
create index if not exists idx_match_prediction_freeze_selected
  on public.match_prediction_freeze_ledger(selected_for_backtest, fixture_date desc);
create index if not exists idx_match_prediction_freeze_model
  on public.match_prediction_freeze_ledger(model_version, captured_at desc);
create index if not exists idx_match_prediction_freeze_season
  on public.match_prediction_freeze_ledger(season_key, league, captured_at desc);

-- Freeze Ledger jest niezmienny po INSERT. Service role nadal może dodawać kolejne wpisy,
-- ale żaden istniejący snapshot nie może zostać przepisany ani usunięty.
create or replace function public.betai_prevent_freeze_mutation_v182()
returns trigger
language plpgsql
as $$
begin
  raise exception 'Bet+AI Prediction Freeze Ledger is append-only';
end;
$$;

drop trigger if exists trg_betai_freeze_no_update_v182 on public.match_prediction_freeze_ledger;
create trigger trg_betai_freeze_no_update_v182
before update on public.match_prediction_freeze_ledger
for each row execute function public.betai_prevent_freeze_mutation_v182();

drop trigger if exists trg_betai_freeze_no_delete_v182 on public.match_prediction_freeze_ledger;
create trigger trg_betai_freeze_no_delete_v182
before delete on public.match_prediction_freeze_ledger
for each row execute function public.betai_prevent_freeze_mutation_v182();

