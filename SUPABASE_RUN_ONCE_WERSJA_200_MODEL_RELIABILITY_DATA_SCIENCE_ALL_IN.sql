create table if not exists public.match_fixture_integrity (
  fixture_id text primary key,
  canonical_fixture_date timestamptz null,
  home_team text not null default '',
  away_team text not null default '',
  league text not null default '',
  country text not null default '',
  duplicate_key text null,
  season_key text null,
  integrity_status text not null default 'clear',
  leakage_status text not null default 'clear',
  freeze_count integer not null default 0,
  settlement_count integer not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint match_fixture_integrity_status_check check (integrity_status in ('clear','review','blocked')),
  constraint match_fixture_leakage_status_check check (leakage_status in ('clear','blocked','review'))
