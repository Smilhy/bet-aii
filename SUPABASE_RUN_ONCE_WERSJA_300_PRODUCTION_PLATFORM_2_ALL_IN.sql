create table if not exists public.match_push_subscriptions_v300 (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  endpoint text not null unique,
  subscription jsonb not null,
  user_agent text null,
  active boolean not null default true,
  last_success_at timestamptz null,
  last_error_at timestamptz null,
  last_error text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_match_push_subscriptions_v300_user
  on public.match_push_subscriptions_v300(user_id, active, updated_at desc);

create table if not exists public.match_push_delivery_v300 (
  id bigint generated by default as identity primary key,
  alert_id bigint not null,
  subscription_id bigint not null,
  status text not null default 'pending',
  attempts integer not null default 0,
  last_status_code integer null,
  last_error text null,
  sent_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint match_push_delivery_v300_unique unique (alert_id, subscription_id),
  constraint match_push_delivery_v300_status_check check (status in ('pending','sent','retry','dead'))
);

create index if not exists idx_match_push_delivery_v300_status
  on public.match_push_delivery_v300(status, updated_at asc);


