  status text not null default 'pending',
  attempts integer not null default 0,
  payload jsonb not null default '{}'::jsonb,
  last_error text null,
  next_attempt_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint match_backfill_queue_v300_unique unique (fixture_id, backfill_type),
  constraint match_backfill_queue_v300_status_check check (status in ('pending','processing','done','retry','dead'))
);

create index if not exists idx_match_backfill_queue_v300_work
  on public.match_backfill_queue_v300(status, priority desc, next_attempt_at asc, created_at asc);

