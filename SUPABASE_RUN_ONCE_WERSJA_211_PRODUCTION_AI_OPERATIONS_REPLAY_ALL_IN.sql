create table if not exists public.match_odds_timeline (
  id bigint generated by default as identity primary key,
  fixture_id text not null,
  fixture_date timestamptz null,
  home_team text not null default '',
  away_team text not null default '',
  league text not null default '',
  market_key text not null,
  bookmaker text not null default '',
  odds numeric(10,4) not null check (odds > 1),
  model_probability numeric(7,3) null,
  fair_odds numeric(10,4) null,
  edge_pp numeric(8,3) null,
  snapshot_window text not null,
  target_minutes_before integer not null,
  actual_minutes_before numeric(10,2) null,
  source text not null default 'API-Football /odds',
  is_closing_candidate boolean not null default false,
  captured_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  constraint match_odds_timeline_window_check
    check (snapshot_window in ('T24H','T6H','T1H','T15M','CLOSING','MANUAL')),
  constraint match_odds_timeline_unique_quote
    unique (fixture_id, snapshot_window, market_key, bookmaker)
);

create index if not exists idx_match_odds_timeline_fixture_time
  on public.match_odds_timeline(fixture_id, captured_at asc);

create index if not exists idx_match_odds_timeline_window
  on public.match_odds_timeline(snapshot_window, fixture_date desc);

create index if not exists idx_match_odds_timeline_closing
  on public.match_odds_timeline(fixture_id, is_closing_candidate, captured_at desc)
  where is_closing_candidate = true;

