create table if not exists public.match_ops_runs (
  id bigint generated by default as identity primary key,
  run_type text not null,
  status text not null default 'running',
  started_at timestamptz not null default now(),
  finished_at timestamptz null,
  duration_ms integer null,
  metrics jsonb not null default '{}'::jsonb,
  error_text text null,
  created_at timestamptz not null default now(),
  constraint match_ops_runs_type_check
    check (run_type in ('odds_snapshot','settlement','model_rebuild','anomaly_scan','replay_read','performance_explorer','api_health')),
  constraint match_ops_runs_status_check
    check (status in ('running','ok','partial','error','skipped'))
);

create index if not exists idx_match_ops_runs_type_time
  on public.match_ops_runs(run_type, started_at desc);

create index if not exists idx_match_ops_runs_status_time
  on public.match_ops_runs(status, started_at desc);

